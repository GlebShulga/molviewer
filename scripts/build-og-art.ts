/**
 * Fetch and store the geometry for the molecule pictures on the social cards
 * (site/moleculeArt.ts, site/build/ogCards.ts) into data/og-art/*.json.
 *
 * Run by hand and commit the result, so `pnpm build` never calls RCSB,
 * AlphaFold DB or PubChem:
 *   pnpm og:art                       fetch art for curated entries that have none
 *   pnpm og:art --only=4HHB,caffeine  (re)fetch just these (PDB IDs, UniProt accessions or compound slugs)
 *   pnpm og:art --force               refetch everything
 * Entries that left the catalog are dropped.
 *
 * Sources:
 * - PDB: RCSB ModelServer, CA and P atoms of model 1 (two requests: a combined
 *   `CA,P` filter returns nothing, and without model_nums NMR entries return
 *   every model). Falls back to the full mmCIF.
 * - AlphaFold: the model's mmCIF (CA atoms, pLDDT from the B-factor column).
 * - Compounds: PubChem 3D SDF, falling back to 2D, like the app
 *   (src/utils/structureLoader.ts).
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { HttpError, fetchJson, fetchText, mapLimit } from './lib/http';
import { ballStickArt, beadArt, type Vec } from './lib/ogArtGeometry';
import { parseMMCIF } from '../src/parsers/mmcifParser';
import { parseSDF } from '../src/parsers/sdfParser';
import { PLDDT_BANDS } from '../src/colors/domains/plddt';
import type { Atom } from '../src/types';
import type { BallStickArt, BeadArt, OgArtFile } from '../site/moleculeArt';
import type { AfSeed, Compound, PdbSeed } from '../site/dataTypes';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = resolve(ROOT, 'data/og-art');
const CONCURRENCY = 2;

const args = process.argv.slice(2);
const FORCE = args.includes('--force');
const ONLY = new Set(
  (args.find((a) => a.startsWith('--only='))?.slice('--only='.length) ?? '')
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)
);

const COMMENT = 'Generated by scripts/build-og-art.ts (pnpm og:art). Geometry for the social card pictures, see site/moleculeArt.ts.';

/** Phosphate ions and similar: their P is not a nucleic acid backbone atom. */
const NON_NUCLEIC_P = new Set(['PO4', 'PO3', 'PI', '2HP', 'H2P']);

const readJson = async <T>(path: string): Promise<T> => JSON.parse(await readFile(path, 'utf8')) as T;

async function readArt<T>(name: string): Promise<Record<string, T>> {
  try {
    return (await readJson<OgArtFile<T>>(resolve(OUT_DIR, name))).entries;
  } catch {
    return {};
  }
}

/** One entry per line, sorted, so diffs show which entries changed. */
async function writeArt<T>(name: string, entries: Record<string, T>): Promise<number> {
  const keys = Object.keys(entries).sort();
  const lines = keys.map((k) => `    ${JSON.stringify(k)}: ${JSON.stringify(entries[k])}`);
  const text = `{\n  "_comment": ${JSON.stringify(COMMENT)},\n  "entries": {\n${lines.join(',\n')}\n  }\n}\n`;
  await writeFile(resolve(OUT_DIR, name), text, 'utf8');
  return Buffer.byteLength(text);
}

function residueBeads(atoms: Atom[]): Atom[] {
  return atoms.filter(
    (a) => (a.name === 'CA' && a.element.toUpperCase() === 'C') || (a.name === 'P' && !NON_NUCLEIC_P.has(a.residueName ?? ''))
  );
}

async function pdbAtoms(id: string): Promise<Atom[]> {
  const lower = id.toLowerCase();
  try {
    const query = (name: string) =>
      fetchText(`https://models.rcsb.org/v1/${lower}/atoms?label_atom_id=${name}&model_nums=1&encoding=cif`).then(
        (text) => parseMMCIF(text, { inferBonds: false }).atoms
      );
    const [ca, p] = await Promise.all([query('CA'), query('P')]);
    const beads = residueBeads([...ca, ...p]);
    if (beads.length) return beads;
  } catch (err) {
    if (err instanceof HttpError && err.status === 404) throw err;
    // Any other ModelServer problem: try the full file below.
  }
  const text = await fetchText(`https://files.rcsb.org/download/${id}.cif`);
  return residueBeads(parseMMCIF(text, { inferBonds: false }).atoms);
}

async function pdbArt(id: string): Promise<BeadArt | null> {
  const atoms = await pdbAtoms(id);
  const chains: string[] = [];
  const index = new Map<string, number>();
  const points = atoms.map((a) => {
    const chain = a.chainId ?? '';
    if (!index.has(chain)) {
      index.set(chain, chains.length);
      chains.push(chain);
    }
    return { x: a.x, y: a.y, z: a.z, group: index.get(chain)! };
  });
  // The group is stored in one byte (scripts/lib/ogArtGeometry.ts).
  if (chains.length > 256) console.warn(`WARN  PDB ${id}: ${chains.length} chains; chains from #256 on share one color`);
  return beadArt(points, chains);
}

interface AfPrediction {
  uniprotAccession?: string;
  cifUrl?: string;
}

/** pLDDT band index, 0 = very high (same boundaries as getPlddtColor). */
const plddtBand = (plddt: number) => {
  const i = PLDDT_BANDS.findIndex((b) => plddt > b.min);
  return i < 0 ? PLDDT_BANDS.length - 1 : i;
};

async function afArt(id: string): Promise<BeadArt | null> {
  const meta = await fetchJson<AfPrediction[] | AfPrediction>(`https://alphafold.ebi.ac.uk/api/prediction/${id}`);
  const entries = Array.isArray(meta) ? meta : [meta];
  const cifUrl = (entries.find((e) => e?.uniprotAccession === id) ?? entries[0])?.cifUrl;
  if (!cifUrl) throw new Error('no cifUrl');
  const atoms = parseMMCIF(await fetchText(cifUrl), { inferBonds: false }).atoms.filter((a) => a.name === 'CA');
  return beadArt(atoms.map((a) => ({ x: a.x, y: a.y, z: a.z, group: plddtBand(a.tempFactor ?? 0) })));
}

async function compoundArt(cid: number): Promise<BallStickArt | null> {
  const base = `https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/cid/${cid}/SDF`;
  let sdf: string;
  try {
    sdf = await fetchText(`${base}?record_type=3d`);
  } catch (err) {
    if (!(err instanceof HttpError && err.status === 404)) throw err;
    sdf = await fetchText(`${base}?record_type=2d`);
  }
  const molecule = parseSDF(sdf);
  const atoms: (Vec & { element: string })[] = molecule.atoms.map((a) => ({ x: a.x, y: a.y, z: a.z, element: a.element }));
  return ballStickArt(atoms, molecule.bonds.map((b) => [b.atom1Index, b.atom2Index]));
}

async function update<T>(
  label: string,
  file: string,
  ids: string[],
  fetchOne: (id: string) => Promise<T | null>
): Promise<string[]> {
  const existing = await readArt<T>(file);
  const wanted = new Set(ids);
  const entries: Record<string, T> = {};
  for (const [k, v] of Object.entries(existing)) if (wanted.has(k)) entries[k] = v;
  const dropped = Object.keys(existing).length - Object.keys(entries).length;

  const todo = ids.filter((id) => (ONLY.size ? ONLY.has(id) : FORCE || !entries[id]));
  console.log(`${label}: ${todo.length} to fetch, ${Object.keys(entries).length} kept${dropped ? `, ${dropped} dropped` : ''}`);
  const failures: string[] = [];
  let done = 0;
  await mapLimit(todo, CONCURRENCY, async (id) => {
    try {
      const art = await fetchOne(id);
      if (art) entries[id] = art;
      else failures.push(`${label} ${id}: no atoms`);
    } catch (err) {
      failures.push(`${label} ${id}: ${err instanceof Error ? err.message : String(err)}`);
    }
    if (++done % 25 === 0) console.log(`  ${label}: ${done}/${todo.length}`);
  });
  const bytes = await writeArt(file, entries);
  console.log(`  wrote data/og-art/${file}: ${Object.keys(entries).length} entries, ${(bytes / 1024).toFixed(0)} KB`);
  return failures;
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  const pdbs = (await readJson<{ pdbs: PdbSeed[] }>(resolve(ROOT, 'data/popularPdbs.json'))).pdbs;
  const afs = (await readJson<{ entries: AfSeed[] }>(resolve(ROOT, 'data/alphafold.json'))).entries;
  const compounds = (await readJson<{ compounds: Compound[] }>(resolve(ROOT, 'data/compounds.json'))).compounds;
  const cidBySlug = new Map(compounds.map((c) => [c.slug, c.cid]));

  const failures = [
    ...(await update('PDB', 'pdb.json', pdbs.map((p) => p.id), pdbArt)),
    ...(await update('AlphaFold', 'af.json', afs.map((a) => a.id), afArt)),
    ...(await update('Compound', 'compound.json', compounds.map((c) => c.slug), (slug) => compoundArt(cidBySlug.get(slug)!))),
  ];
  for (const f of failures) console.warn(`WARN  ${f}`);
  console.log(failures.length ? `Done with ${failures.length} failure(s); those cards stay text-only.` : 'Done.');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
